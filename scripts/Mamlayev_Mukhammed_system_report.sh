#!/bin/bash
# =====================================================================
#  Mamlayev_Mukhammed_system_report.sh
#  Author : Mukhammed Mamlayev
#  Project: mamlayev-mukhammed-student-api
#  Purpose: Collect basic system information (user, OS, kernel, CPU,
#           memory, disk) and save it to the personal log file.
#
#  Usage  : ./scripts/Mamlayev_Mukhammed_system_report.sh [LOG_FILE]
#           $1 (optional) - path of the log file. If it is not given,
#           logs/Mamlayev_Mukhammed_system_report.log is used.
# =====================================================================

set -u

STUDENT_NAME="Mukhammed Mamlayev"
STUDENT_SURNAME="Mamlayev"

# Resolve the project directory from the script location so the script
# works no matter which directory it is started from.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
LOG_FILE="${1:-$PROJECT_DIR/logs/Mamlayev_Mukhammed_system_report.log}"

mkdir -p "$(dirname "$LOG_FILE")"

section() {
    echo
    echo "---------- $1 ----------"
}

os_name() {
    if [ -r /etc/os-release ]; then
        . /etc/os-release
        echo "${PRETTY_NAME:-$NAME}"
    else
        uname -s
    fi
}

cpu_info() {
    if command -v lscpu >/dev/null 2>&1; then
        lscpu | grep -E '^(Architecture|Model name|CPU\(s\)|Thread\(s\) per core|Core\(s\) per socket)' \
            | sed 's/  */ /g'
    else
        grep -m1 'model name' /proc/cpuinfo 2>/dev/null
        echo "CPU(s): $(nproc 2>/dev/null)"
    fi
    echo "Load average (1/5/15 min): $(cut -d' ' -f1-3 /proc/loadavg 2>/dev/null)"
}

memory_info() {
    if command -v free >/dev/null 2>&1; then
        free -h
    else
        grep -E 'MemTotal|MemAvailable' /proc/meminfo
    fi
}

generate_report() {
    echo "====================================================="
    echo " SYSTEM REPORT - ${STUDENT_NAME} (${STUDENT_SURNAME})"
    echo "====================================================="
    echo "Student full name : ${STUDENT_NAME}"
    echo "Date and time     : $(date '+%Y-%m-%d %H:%M:%S %Z')"
    echo "Current user      : $(whoami)"
    echo "Hostname          : $(hostname)"
    echo "Operating system  : $(os_name)"
    echo "Kernel version    : $(uname -r)"
    echo "Architecture      : $(uname -m)"

    section "CPU information"
    cpu_info

    section "Memory information"
    memory_info

    section "Disk usage (all real filesystems)"
    df -h -x tmpfs -x devtmpfs -x overlay 2>/dev/null || df -h

    section "Available disk space for the project directory"
    df -h --output=source,size,used,avail,pcent,target "$PROJECT_DIR" 2>/dev/null \
        || df -h "$PROJECT_DIR"
    echo "Project size: $(du -sh "$PROJECT_DIR" 2>/dev/null | cut -f1)"

    echo
    echo "Report generated by ${STUDENT_NAME}"
    echo "====================================================="
    echo
}

# tee shows the report in the terminal and appends (-a) it to the log,
# so every run is kept in the history of the log file.
generate_report | tee -a "$LOG_FILE"

echo "Report saved to: $LOG_FILE"
